function applyLocale(lang){
 if(updating)return;updating=true;
 try{document.documentElement.lang=langNames[lang]||'zh-Hant';document.documentElement.dataset.ubLocale=lang;
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
   const node=walker.currentNode, parent=node.parentElement;
   if(!parent||isUserContent(parent)||parent.closest('script,style,pre,code,textarea'))continue;
   const original=node.nodeValue, core=original.trim();if(!core)continue;
   const key=originals(core);if(!ui[key])continue;
   const translated=lang==='zh-TW'?key:translationByLanguage[lang]?.get(key)||key;
   if(core!==translated)node.nodeValue=original.replace(core,translated);
  }
  document.querySelectorAll('[placeholder]').forEach(input=>{
   const now=input.getAttribute('placeholder');
   const key=Object.keys(inputTexts).find(k=>now===k||now===inputTexts[k]||now===localInputJa[k]);
   if(key)input.setAttribute('placeholder',lang==='en'?inputTexts[key]:lang==='ja'?localInputJa[key]:key);
  });
 }finally{updating=false}
}
